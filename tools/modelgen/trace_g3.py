"""
G3A3（固定ストック・細身のハンドガード）の側面形を作者提供の真横写真（左側面・銃口が左、白背景、1456×772px）から
トレースし、g3_outline.py（座標データ）を書き出す。

  python3 trace_g3.py <左側面の写真.png>

縮尺は全長 1025mm（公表値）に合わせた 1.3805px/mm（銃口 x=20〜床尾 x=1435）。この縮尺で照準半径は 559mm
（公表値 572mm と 2% 差）、弾倉の前後 76mm・7.62×51mm 弾 71mm がボルトの前面（銃身 450mm から逆算）と弾倉の後ろの壁の間に
収まることで食い違いが無いのを確かめた。
写真は左右反転して銃口を +x にそろえ、反転後の x=600 がトリガー（Z=0）、y=550 がグリップの下端（Y=0）。
背景の灰色が 230〜245 なので、しきい値は 225（200 だと銃身の光った所で影絵が切れる）。
部品の境目は写真に mm 目盛りを重ねて読んだ（REGIONS）。写真はリポジトリに入れない（第三者の著作物）。
"""
import sys
from pathlib import Path

from photo_trace import Silhouette

K, X0, Y0 = 1.3805, 600.0, 550.0
BORE_Y = 177.0          # 銃身の軸（消炎器・銃身の上下の縁の中点）


def rect(z0, z1, y0, y1):
    return [(z0, y0), (z1, y0), (z1, y1), (z0, y1)]


REGIONS = {
    # 名前: (範囲, 除く範囲, 穴として残す最小の面積 mm²)。Z は銃口側が負
    "butt": (rect(395.0, 430.0, 45.0, 195.0), (), 1e9),           # 床尾板（黒いゴム）
    "stock": (rect(150.0, 396.0, 45.0, 210.0), (), 1e9),           # 固定ストック（樹脂。受け部の後端キャップに差さる）
    "end_cap": (rect(100.0, 151.0, 136.0, 210.0), (), 1e9),        # 受け部の後端（ストックの受け。下に 2 本のピン）
    "lower_housing": ([(-58.0, 104.0), (52.0, 104.0), (52.0, 138.0), (88.0, 138.0), (88.0, 132.5), (100.0, 132.5),
                       (100.0, 160.0), (-58.0, 160.0)], (), 1e9),   # トリガーハウジング（グリップの上まで）
    # グリップ（上の後ろの端 Z 88〜125 の細い帯はハウジングの下の縁なので含めない。含めると膨らませたときに潰れる）
    "grip": ([(40.0, -5.0), (125.0, -5.0), (125.0, 132.5), (88.0, 132.5), (88.0, 139.0), (52.0, 139.0), (52.0, 104.0),
              (40.0, 104.0)], (), 1e9),
    "magwell": (rect(-160.0, -58.0, 106.0, 160.0), (), 1e9),       # 弾倉の受け（受け部と一体の板金。前の端が斜め）
    "magazine": (rect(-165.0, -80.0, -6.0, 106.5), (), 1e9),       # 20 発弾倉（弾倉の受けの下に見える部分）
    "trigger_guard": (rect(-50.0, 40.0, 66.0, 104.5), (rect(-8.0, 12.0, 73.0, 105.0),), 40.0),
    "trigger": (rect(-8.0, 12.0, 73.0, 104.5), (), 1e9),
    "mag_release": (rect(-80.0, -60.0, 85.0, 106.5), (), 1e9),     # 弾倉止めのレバー（弾倉の後ろの爪）
    "handguard": (rect(-484.0, -205.0, 150.0, 198.5), (), 1e9),    # 細身のハンドガード（後ろが太く前が細い）
    "front_sight": (rect(-505.0, -475.0, 160.0, 250.0), (), 1e9),  # 照星（銃身を抱く台・コッキングチューブの先・フード）
    "rear_sight": (rect(45.0, 105.0, 204.5, 235.0), (), 1e9),      # 照門（台と回転ドラム）
}


def main(photo):
    sil = Silhouette(photo, K, X0, Y0, flip=True, thr=225, blur=0.6)
    out = ['"""G3A3 の側面形（trace_g3.py が写真から書き出した座標。手で編集しない）。単位 mm、(Z, Y)。"""', ""]
    for name, (region, minus, hole) in REGIONS.items():
        out.append(f"{name.upper()} = {sil.part(region, minus=minus, min_hole=hole)!r}")
    out.append(f"MUZZLE_R = {sil.radius_profile(-500.0, -607.0, BORE_Y, step=1.5, band=16.0)!r}")
    Path(__file__).with_name("g3_outline.py").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote g3_outline.py")


if __name__ == "__main__":
    main(sys.argv[1])
